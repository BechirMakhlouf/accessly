export function getServiceIconUrl(service: AccessableService): string | null {
  const domain = SERVICE_DOMAINS[service];
  if (!domain) return null;
  return `https://www.google.com/s2/favicons?domain=${domain}&sz=64`;
}

export function getServiceDomain(service: AccessableService): string | null {
  return SERVICE_DOMAINS[service];
}

